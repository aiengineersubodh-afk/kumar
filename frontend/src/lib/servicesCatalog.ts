// Helper functions for easy lookup
export function getAllCategories(): ServiceCategory[] {
  return SERVICE_CATEGORIES;
}

export function getAllSubServices(): SubService[] {
  const list: SubService[] = [];
  for (const cat of SERVICE_CATEGORIES) {
    list.push(...cat.subServices);
  }
  return list;
}

export function getSubServiceBySlug(slug: string): SubService | null {
  for (const cat of SERVICE_CATEGORIES) {
    const found = cat.subServices.find((s) => s.slug === slug);
    if (found) return found;
  }
  return null;
}

export function getCategoryBySlug(slug: string): ServiceCategory | null {
  return SERVICE_CATEGORIES.find((c) => c.slug === slug) || null;
}
